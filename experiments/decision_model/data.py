"""Decision inputs and rewards shared by data collection and the search caller."""

import math
import copy

ACTIONS = ("Refine", "Explore", "Crossover")
GAIN_LIMITS = (0.001, 0.005, 0.02)
DEFAULT_SUPPORT = (0.0, 0.0005, 0.003, 0.0125, 0.03)


def questions(horizon):
    if horizon not in (1, 2, 4):
        raise ValueError("supported horizons are one candidate, an ordinary request, or four candidates")
    condition = {1: "one candidate generated by the proposed action",
        2: "one ordinary request: the proposed action, plus its automatic Repair if a new program fails "
           "and the remaining candidate budget permits; no subsequent Refine or Develop",
        4: "at most four candidates: the proposed action first, then Refine; "
           "Repair, failures and duplicates also consume candidates"}[horizon]
    result = {
        "new_valid": {"type": "noul", "instructions":
            f"Will {condition} include a previously unseen program accepted by the fixed training evaluator?"},
        "improve_parent": {"type": "noul", "instructions":
            f"Will {condition} produce a previously unseen valid program with a lower score than the starting parent?"},
        "frontier_gain": {"type": "score", "instructions":
            f"Predict the best new valid program obtained from {condition}. "
            "Lower training scores are better. Its normalized frontier gain is "
            "max(0, frontier_score_before - best_new_score) / score_scale. "
            "Failed, duplicated and non-improving results have zero gain.",
            "criteria": ["zero gain", "positive gain below 0.001", "gain from 0.001 to below 0.005",
                         "gain from 0.005 to below 0.02", "gain at least 0.02"]},
    }
    if horizon == 2:
        return {"frontier_gain": result["frontier_gain"], "repair_used": {"type": "noul", "instructions":
            f"Will {condition} consume a second candidate through an automatic Repair? "
            "A valid first candidate, delivery failure, duplicate, skipped repair or exhausted budget uses one candidate."}}
    return result


def delivered_request(first, following, programs, search_budget):
    """Observed delivery and cost; an unfinished repair is right-censored."""
    if first["action"] not in ACTIONS or first.get("repair_of") is not None:
        raise ValueError("expected the initial ordinary action")
    if following is not None and following["id"] != first["id"] + 1:
        raise ValueError("following candidate is not adjacent")
    node = programs.get(first.get("program_id"))
    could_repair = (node is not None and node["id"] == first["id"] and not node["valid"]
                    and first["id"] < search_budget)
    if could_repair and following is None:
        return None
    repair = (following if following is not None and first.get("program_id") is not None
              and following.get("repair_of") == first["program_id"] else None)
    if repair is not None and (not could_repair or repair["action"] != "Repair"):
        raise ValueError("inconsistent automatic repair")
    delivered = []
    for attempt in (first, repair):
        if attempt is not None and attempt["status"] == "valid":
            program = programs.get(attempt["program_id"])
            if program is None or not program["valid"] or program["id"] != attempt["id"]:
                raise ValueError("valid delivery needs the newly evaluated program")
            delivered.append(program["fitness"])
    return {"fitnesses": delivered, "candidate_cost": 1 + int(repair is not None),
            "attempt_ids": [first["id"]] + ([repair["id"]] if repair is not None else [])}


def gain_level(gain):
    if not math.isfinite(gain) or gain < 0:
        raise ValueError("gain must be finite and nonnegative")
    return 0 if gain == 0 else 1 + sum(gain >= limit for limit in GAIN_LIMITS)


def outcome(parent_fitness, frontier_fitness, new_fitnesses, score_scale=1.0):
    from traceaad.common.selection import better

    if not math.isfinite(score_scale) or score_scale <= 0:
        raise ValueError("score_scale must be finite and positive")
    if not all(math.isfinite(x) for x in [parent_fitness, frontier_fitness, *new_fitnesses]):
        raise ValueError("nonfinite fitness")
    best = min(new_fitnesses) if new_fitnesses else None
    gain = ((frontier_fitness - best) / score_scale
            if best is not None and better(best, frontier_fitness) else 0.0)
    return {"new_valid": best is not None,
            "improve_parent": best is not None and better(best, parent_fitness),
            "frontier_gain": gain_level(gain)}, gain


def request_state(task, task_text, template, programs, attempts, parent_id, reference_id,
                  action, cutoff, search_budget, horizon=1, phase="ordinary", score_scale=1.0,
                  prompt_policy="v1022"):
    from traceaad.common.history import code_diff
    from traceaad.common.selection import experience
    from traceaad.v10_22.prompts import PromptBuilder as V1022Prompts
    from traceaad.v10_23.prompts import PromptBuilder as V1023Prompts

    policies = {"v1022": ("TraceAAD V10.22", V1022Prompts), "v1023": ("TraceAAD V10.23", V1023Prompts)}
    if action not in ACTIONS or horizon not in (1, 2, 4) or prompt_policy not in policies:
        raise ValueError("unsupported action, horizon or prompt policy")
    policy_name, PromptBuilder = policies[prompt_policy]
    past_programs = {i: p for i, p in programs.items() if i <= cutoff}
    past_attempts = {i: a for i, a in attempts.items() if i <= cutoff}
    parent = past_programs[parent_id]
    if not parent["valid"] or not parent.get("code"):
        raise ValueError("parent must be valid with complete source")
    reference = past_programs[reference_id] if action == "Crossover" else None
    if reference is not None and (not reference["valid"] or not reference.get("code")):
        raise ValueError("reference must be valid with complete source")
    tried, improved = experience(past_attempts, past_programs)
    recent = []
    for attempt in sorted(past_attempts.values(), key=lambda a: a["id"], reverse=True):
        if attempt.get("parent_id") != parent_id or attempt.get("repair_of") is not None:
            continue
        child = past_programs.get(attempt.get("program_id"))
        recent.append({"action": attempt["action"], "status": attempt["status"],
                       "fitness": child["fitness"] if child and child["valid"] else None,
                       "code_diff_excerpt": code_diff(parent["code"], child["code"])[:1200]
                       if child and child.get("code") else None})
        if len(recent) == 2:
            break
    formation = []
    node = parent
    for _ in range(2):
        previous = past_programs.get(node.get("parent_id"))
        if previous is None:
            break
        formation.append({"action": node["action"], "fitness": node["fitness"],
                          "code_diff_excerpt": code_diff(previous["code"], node["code"])[:1200]})
        node = previous
    return {
        "task": task, "task_and_interface": task_text, "target_function": template,
        "generation_policy": policy_name, "decision_phase": phase,
        "score_scale": score_scale,
        "proposed_action": action, "development_budget_candidates": horizon,
        "action_instruction": {"Refine": PromptBuilder.REFINE, "Explore": PromptBuilder.EXPLORE,
                               "Crossover": PromptBuilder.CROSSOVER}[action],
        "analysis_instruction": PromptBuilder.ANALYSIS[action],
        "attempts_used": cutoff, "remaining_candidates": max(0, search_budget - cutoff),
        "frontier_score_before": min(p["fitness"] for p in past_programs.values() if p["valid"]),
        "parent": {"code": parent["code"], "fitness": parent["fitness"], "depth": parent["depth"],
                   "previous_tries": tried[parent_id], "previous_improvements": improved[parent_id]},
        "reference": {"code": reference["code"], "fitness": reference["fitness"]} if reference else None,
        "recent_attempts": recent, "formation": list(reversed(formation)),
    }


def expected_gain(answer, support):
    probabilities = answer["probabilities"]
    if len(support) != 5 or set(probabilities) != {str(i) for i in range(5)}:
        raise ValueError("expected five gain levels")
    values = [float(probabilities[str(i)]) for i in range(5)]
    if not all(math.isfinite(p) and 0 <= p <= 1 for p in values) or abs(sum(values) - 1) > 0.002:
        raise ValueError("invalid gain probabilities")
    if not all(math.isfinite(x) and x >= 0 for x in support):
        raise ValueError("invalid reward support")
    return sum(p * reward for p, reward in zip(values, support))


def expected_request_cost(answer, remaining_candidates):
    probabilities = answer["probabilities"]
    if set(probabilities) != {"true", "false"} or remaining_candidates < 1:
        raise ValueError("invalid repair probabilities or remaining budget")
    values = [float(probabilities[name]) for name in ("true", "false")]
    if not all(math.isfinite(p) and 0 <= p <= 1 for p in values) or abs(sum(values) - 1) > 0.002:
        raise ValueError("invalid repair probabilities")
    return min(1 + values[0], remaining_candidates)


def fit_record(record, encoded_length, max_length):
    """Remove older history excerpts deliberately; never cut parent or reference source."""
    record = copy.deepcopy(record)
    while encoded_length(record) >= max_length:
        state = record["state"]
        if state["formation"]:
            state["formation"].pop(0)
        elif state["recent_attempts"]:
            state["recent_attempts"].pop(0)
        else:
            raise ValueError("complete parent/reference and schema exceed model context")
    return record
